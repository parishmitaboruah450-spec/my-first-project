"""Synthesise the narration with Kokoro-82M (via kokoro-onnx) and write sanyogita/voice.js.

usage: python tts.py <model.onnx> <voices.npz> <clip-dir>

Indian names are given hand-written pronunciations (IPA, in the style espeak-ng
produces for Kokoro), because a phonemizer guesses them from English spelling.
"""
import json, re, sys
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = Path(__file__).resolve().parent
SAY = {
    'Sanyogita': 'sʌnjˈoʊɡiːtɑː', 'Sanjogita': 'sʌndʒˈoʊɡiːtɑː', 'Samyukta': 'sˈʌmjʊktɑː',
    'Prithviraja': 'pɹˌɪtvɪɹˈɑːdʒə', 'Prithviraj': 'pɹˈɪtvɪɹˌɑːdʒ', 'Chauhan': 'tʃˈaʊhɑːn',
    'Jaichand': 'dʒˈeɪtʃʌnd', 'Kannauj': 'kənˈɔːdʒ', 'Ganga': 'ɡˈʌŋɡɑː', 'Ajmer': 'ʌdʒmˈeɪɹ',
    'swayamvara': 'swˈʌjəmvəɹ', 'Tarain': 'təɹˈɑːɪn', 'Raso': 'ɹˈɑːsoʊ', 'Chand': 'tʃˈʌnd',
    'Bardai': 'bəɹdˈɑːi', 'Vijaya': 'vˈɪdʒəjə', 'Jayanaka': 'dʒəjˈɑːnəkə', 'Gahadavala': 'ɡəhˈɑːdəvˌɑːlə',
    'Varanasi': 'vɑːɹˈɑːnəsi', 'Harishchandra': 'hˌʌɹɪʃtʃˈʌndɹə', 'Chandawar': 'tʃˈʌndəvɑːɹ',
    'samistlei': 'sˈæmɪstleɪ', 'Rani': 'ɹˈɑːni', 'Raja': 'ɹˈɑːdʒɑː', 'Ghor': 'ɡˈoʊɹ',
}
WORD = re.compile(r"\b(" + "|".join(sorted(SAY, key=len, reverse=True)) + r")('s)?\b")


def phonemes(k, text, lang):
    out, pos = [], 0
    for m in WORD.finditer(text):
        plain = text[pos:m.start()]
        article = re.search(r'(^|\s)a\s*$', plain)          # "a swayamvara": a lone "a" before a name
        if article:
            plain = plain[:article.start()] + ' '
        if plain.strip():
            ph = k.tokenizer.phonemize(plain, lang).strip()
            # keep the punctuation that ends a plain chunk; the phonemizer can drop it
            tail = re.search(r'[,.;:!?—…]\s*$', plain)
            if tail and not ph.endswith(tail.group(0).strip()):
                ph += tail.group(0).strip().replace('—', ',').replace('…', '.')
            out.append(ph)
        if article:
            out.append('ɐ')
        out.append(SAY[m.group(1)] + ('z' if m.group(2) else ''))
        pos = m.end()
    rest = text[pos:]
    if rest.strip():
        ph = k.tokenizer.phonemize(rest, lang).strip() if re.search(r'\w', rest) else ''
        punct = re.sub(r'[^,.;:!?]', '', rest.replace('—', ',').replace('…', '.'))
        out.append(ph if ph else punct)
    return ' '.join(p for p in out if p)


def main():
    model, voices, clips = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    clips.mkdir(parents=True, exist_ok=True)
    spec = json.loads((HERE / 'narration.json').read_text(encoding='utf-8'))
    k = Kokoro(model, voices)
    lines = []
    for ln in spec['lines']:
        say = ln.get('say', ln['text']).replace('…', '...').replace('—', ',')
        ph = phonemes(k, say, spec['lang'])
        audio, sr = k.create(ph, voice=spec['voice'], speed=spec['speed'], lang=spec['lang'], is_phonemes=True)
        audio = np.asarray(audio, dtype=np.float32)
        # trim the quiet ends so timing follows the words themselves
        on = np.flatnonzero(np.abs(audio) > 0.01)
        if on.size:
            audio = audio[max(0, on[0] - int(0.03 * sr)): on[-1] + int(0.08 * sr)]
        sf.write(clips / f"{ln['id']}.wav", audio, sr)
        d = round(len(audio) / sr, 3)
        lines.append({'id': ln['id'], 'a': ln['a'], 'd': d, 'text': ln['text'], 'cap': ln.get('cap', True)})
        print(f"{ln['id']}  {d:5.2f}s  {ph[:90]}")
    total = sum(l['d'] for l in lines)
    print(f'speech total {total:.1f}s over {len(lines)} lines')
    js = '/* voice.js (generated by tools/tts.py from tools/narration.json): the narration lines and their spoken lengths. */\n'
    js += 'window.Film.setVoice(' + json.dumps({'voice': spec['voice'], 'lines': lines}, ensure_ascii=False, indent=1) + ');\n'
    (HERE.parent / 'voice.js').write_text(js, encoding='utf-8')


if __name__ == '__main__':
    main()
